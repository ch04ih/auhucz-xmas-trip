import type { CityId } from './types'
import { foodListUrls } from './places'

export type FoodListCityId = Extract<CityId, 'budapest' | 'vienna' | 'prague'>

export interface FoodListItem {
  name: string
  /** Google 清單上的類型，例如 Hungarian、Brunch */
  kind?: string
  price?: string
  note?: string
  /** 一行到兩行的中文介紹：特色與招牌，不寫何時去吃 */
  intro: string
  /** Google 地圖星等（靜態快照，約 2026/11） */
  rating?: number
  /** Google 評論數 */
  reviews?: number
  /** 暫時停業等狀態 */
  status?: string
  /** App 裡已有介紹時可點開 */
  placeId?: string
  /**
   * 清單用照片 id（對應 public/places/{id}.jpg）。
   * 有 placeId 時可省略，預設用 placeId。
   */
  imageId?: string
  /** 大圖裁切位置（CSS object-position） */
  imagePosition?: string
  /** 照片放大倍率（預設 1） */
  imageScale?: number
  mapsQuery: string
}

export interface FoodListCity {
  id: FoodListCityId
  label: string
  listUrl: string
  items: FoodListItem[]
}

export function foodImageId(item: FoodListItem): string | undefined {
  return item.placeId || item.imageId
}

